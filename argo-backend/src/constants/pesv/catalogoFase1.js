function nivelIndice(n) {
  const i = NIVELES_ORDEN.indexOf(n);
  return i >= 0 ? i : 0;
}

function itemAplicaAlNivel(item, nivelOrg) {
  if (!item.nivelMinimo) return true;
  return nivelIndice(nivelOrg) >= nivelIndice(item.nivelMinimo);
}

function sugerenciaRespuestaItem(item, nivelOrg) {
  if (itemAplicaAlNivel(item, nivelOrg)) return null;
  return { existe: 'no', motivoCodigo: 'no_aplica_nivel' };
}

